const {contextBridge, ipcRenderer} = require('electron');
contextBridge.exposeInMainWorld('opora', {
  claudeState:()=>ipcRenderer.invoke('claude:state'),
  claudeStart:options=>ipcRenderer.invoke('claude:start',options),
  claudeInput:input=>ipcRenderer.invoke('claude:input',input),
  claudeResize:input=>ipcRenderer.invoke('claude:resize',input),
  claudeStop:id=>ipcRenderer.invoke('claude:stop',id),
  claudeSelect:()=>ipcRenderer.invoke('claude:select'),
  claudeClipboard:()=>ipcRenderer.invoke('claude:clipboard'),
  onClaudeEvent:callback=>{const listener=(_,event)=>callback(event);ipcRenderer.on('claude:event',listener);return ()=>ipcRenderer.removeListener('claude:event',listener);},
  openProject: () => ipcRenderer.invoke('project:open'),
  restoreProject: () => ipcRenderer.invoke('project:restore'),
  save: (state,baseBrand,baseState,approvedBrand) => ipcRenderer.invoke('project:save', state,baseBrand,baseState,approvedBrand),
  preview: state => ipcRenderer.invoke('project:preview', state),
  sync: (state,baseBrand,baseState) => ipcRenderer.invoke('project:sync', state,baseBrand,baseState),
  projectSnapshot: () => ipcRenderer.invoke('project:snapshot'),
  projectMap: options => ipcRenderer.invoke('project:map', options),
  workContext: input => ipcRenderer.invoke('workspace:read',input),
  feedbackHistory: input => ipcRenderer.invoke('feedback:history',input),
  feedbackArchive: input => ipcRenderer.invoke('feedback:archive',input),
  feedbackRead: () => ipcRenderer.invoke('feedback:read'),
  feedbackNote: input => ipcRenderer.invoke('feedback:note',input),
  feedbackDecide: input => ipcRenderer.invoke('feedback:decide',input),
  feedbackImage: input => ipcRenderer.invoke('feedback:image',input),
  feedbackImport: input => ipcRenderer.invoke('feedback:import',input),
  feedbackClipboard: input => ipcRenderer.invoke('feedback:clipboard',input),
  scanBrandbook: () => ipcRenderer.invoke('brandbook:scan'),
  applyBrandbook: selection => ipcRenderer.invoke('brandbook:apply', selection),
  reviewBrandbook: state => ipcRenderer.invoke('brandbook:review', state),
  updateInfo: () => ipcRenderer.invoke('updates:info'),
  checkUpdates: () => ipcRenderer.invoke('updates:check'),
  updateDiagnostics: () => ipcRenderer.invoke('updates:diagnostics'),
  downloadUpdate: () => ipcRenderer.invoke('updates:download'),
  installUpdate: () => ipcRenderer.invoke('updates:install'),
  onUpdateProgress: callback => ipcRenderer.on('updates:progress', (_,info) => callback(info)),
  agentInfo: () => ipcRenderer.invoke('agents:info'),
  configureAgent: client => ipcRenderer.invoke('agents:configure', client),
  disconnectAgent: client => ipcRenderer.invoke('agents:disconnect',client),
  agentReports: () => ipcRenderer.invoke('agents:reports'),
  addReferences: () => ipcRenderer.invoke('reference:add'),
  referenceImage: file => ipcRenderer.invoke('reference:image', file),
  copy: text => ipcRenderer.invoke('clipboard:copy', text),
  onCloseRequested: callback => ipcRenderer.on('app:flush', () => callback()),
  readyToClose: () => ipcRenderer.send('app:ready-to-close')
});
