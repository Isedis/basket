const {_electron} = require('playwright-core');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const core = require('../src/core.cjs');
const {Client}=require('@modelcontextprotocol/client');
const {StdioClientTransport}=require('@modelcontextprotocol/client/stdio');

async function main() {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(),'opora-electron-'));
  const project = path.join(temp,'game');
  const profile = path.join(temp,'profile');
  await fs.mkdir(project); await fs.mkdir(profile);
  await fs.writeFile(path.join(project,'project.godot'),'config_version=5\n[application]\nconfig/name="Native game"\n');
  await fs.writeFile(path.join(project,'CLAUDE.md'),'# Existing Claude instructions\nUse existing components.\n');
  const image = path.join(temp,'reference.png');
  await fs.writeFile(image,Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl6X7sAAAAASUVORK5CYII=','base64'));
  await fs.mkdir(path.join(project,'ui'));
  await fs.copyFile(image,path.join(project,'ui/menu.png'));
  await fs.writeFile(path.join(project,'ui/theme.tres'),'[gd_resource type="Theme" format=3]\n[resource]\ndefault_font_size = 20\nButton/colors/font_color = Color(0.1, 0.2, 0.3, 1)\n');
  const entry = path.join(temp,'entry.cjs');
  await fs.writeFile(entry,`require('electron').app.setPath('userData', ${JSON.stringify(profile)});\nrequire(${JSON.stringify(path.join(__dirname,'../desktop/main.cjs'))});\n`);
  let app;
  async function launch() {
    const instance = await _electron.launch({executablePath:require('electron'),args:[entry,'--no-sandbox','--ozone-platform=headless'],timeout:30000});
    await instance.evaluate(({dialog}, {project,image})=>{
      dialog.showOpenDialog = async (_win, options) => ({canceled:false,filePaths:options.properties.includes('openDirectory') ? [project] : [image]});
    },{project,image});
    return instance;
  }
  try {
    app = await launch();
    const png=await app.evaluate(({nativeImage})=>nativeImage.createFromBitmap(Buffer.from([32,64,192,255]),{width:1,height:1}).toPNG().toString('base64'));
    await fs.writeFile(image,Buffer.from(png,'base64'));
    await fs.copyFile(image,path.join(project,'ui/menu.png'));
    const page=await app.firstWindow();
    const errors=[]; page.on('pageerror',error=>errors.push(error.message));
    await page.getByRole('button',{name:'Открыть проект'}).click();
    await page.waitForFunction(()=>document.querySelector('[data-field="brand.palette"]')?.value.includes('#1A334D') && !document.querySelector('[data-action="scan-brand"]')?.disabled);
    assert.match(await page.locator('[data-field="brand.fonts"]').inputValue(),/20 px/);
    assert.equal((await core.loadProject(project)).state.brand.status,'draft');
    assert.equal((await core.loadProject(project)).state.references[0].status,'draft');
    assert.ok((await core.loadProject(project)).state.brand.analysis.imageColors.some(c=>c.hex==='#C04818'));
    await page.locator('nav [data-tab="overview"]').click();
    await page.locator('[data-field="rules"]').fill('Не менять размер кнопок');
    await page.locator('nav [data-tab="brand"]').click();
    await page.getByRole('button',{name:'+ Добавить образцы'}).click();
    await page.locator('[data-ref-status]').first().selectOption('approved');
    await page.waitForFunction(()=>document.querySelector('img')?.naturalWidth > 0);
    await page.locator('[data-field="brand.direction"]').fill('My hand-edited visual direction');
    await page.locator('[data-field="brand.status"]').selectOption('approved');
    await page.getByRole('button',{name:'Пересобрать черновик'}).click();
    await page.getByRole('heading',{name:'Черновик из файлов проекта'}).waitFor();
    assert.equal(await page.locator('[data-brand-field="direction"]').isChecked(),false);
    assert.equal(await page.locator('[data-brand-field="palette"]').isChecked(),false);
    await page.locator('[data-brand-field="palette"]').check();
    await page.getByRole('button',{name:'Применить выбранное'}).click();
    await page.waitForFunction(()=>!document.querySelector('#modal').open);
    assert.equal(await page.locator('[data-field="brand.direction"]').inputValue(),'My hand-edited visual direction');
    assert.equal(await page.locator('[data-field="brand.status"]').inputValue(),'draft');
    assert.equal(await page.locator('[data-ref-status]').first().inputValue(),'approved');
    assert.equal((await core.loadProject(project)).state.references.length,2);
    await page.locator('[data-field="brand.palette"]').fill('Основной текст: #444444 на #333333\n#EEDDBB — светлый акцент');
    await page.getByRole('button',{name:'Проверить брендбук',exact:true}).click();
    const contrastFinding=page.locator('#brand-review-panel .brand-finding').filter({hasText:'Контраст ниже выбранного ориентира'});
    await contrastFinding.getByRole('button',{name:'+ Добавить задачу'}).click();
    assert.equal(await contrastFinding.getByRole('button',{name:'В задачах'}).isDisabled(),true);
    await page.waitForFunction(()=>document.querySelector('#save-status')?.textContent.includes('Сохранено'));
    assert.equal((await core.loadProject(project)).state.tasks.filter(t=>t.brandFindingId?.startsWith('contrast-')).length,1);
    await page.screenshot({path:path.join(__dirname,'../artifacts/brand-review.png'),fullPage:true});
    await page.locator('[data-field="brand.palette"]').fill('Основной текст: #FFFFFF на #333333\n#EEDDBB — светлый акцент');
    await page.getByRole('button',{name:'Проверить брендбук',exact:true}).click();
    assert.ok(!(await page.locator('#brand-review-panel').textContent()).includes('Контраст ниже выбранного ориентира'));
    await page.getByRole('button',{name:'Скопировать разбор →'}).click();
    assert.match(await app.evaluate(({clipboard})=>clipboard.readText()),/Разбор брендбука/);
    await page.keyboard.press('Control+k');
    await page.getByRole('combobox',{name:'Найти команду'}).fill('/context');
    await page.keyboard.press('Enter');
    await page.locator('#context-preview').waitFor();
    assert.match(await page.locator('#context-preview').textContent(),/Не менять размер кнопок/);
    await page.locator('nav [data-tab="brand"]').click();
    await fs.mkdir(path.join(__dirname,'../artifacts'),{recursive:true});
    await page.screenshot({path:path.join(__dirname,'../artifacts/brandbook.png'),fullPage:true});
    const byte=Buffer.from('x');
    const digest=require('node:crypto').createHash('sha256').update(byte).digest('hex');
    await app.evaluate(({session},digest)=>{
      session.fromPartition('opora-updates').protocol.handle('https',request=>{
        if(request.url!=='https://raw.githubusercontent.com/Isedis/basket/opora/updates/latest.json')return new Response('',{status:404});
        return new Response(JSON.stringify({schemaVersion:1,version:'0.7.0',commit:'a'.repeat(40),size:1,sha256:digest,parts:[{name:'Opora-Windows.zip.part01',size:1,sha256:digest}]}),{headers:{'Content-Type':'application/json'}});
      });
    },digest);
    await page.getByRole('button',{name:'Обновления',exact:true}).click();
    await page.getByRole('heading',{name:'Обновления Опоры'}).waitFor();
    await page.getByText('Папка и диагностика',{exact:true}).click();
    await page.getByRole('button',{name:'Скопировать диагностику',exact:true}).click();
    const diagnostics=JSON.parse(await app.evaluate(({clipboard})=>clipboard.readText()));
    assert.equal(diagnostics.currentVersion,'0.7.0');
    assert.equal(diagnostics.installDirectory,path.dirname(require('electron')));
    await page.getByRole('button',{name:'Проверить обновления'}).click();
    await page.getByRole('heading',{name:'У вас актуальная версия'}).waitFor();
    assert.match(await page.locator('#modal-content').textContent(),/0.7.0/);
    await page.getByRole('button',{name:'Закрыть',exact:true}).click();
    await page.locator('nav [data-tab="context"]').click();
    await page.getByRole('button',{name:'Обновить файлы проекта'}).click();
    await page.getByRole('button',{name:'Обновить эти файлы'}).click();
    await page.waitForFunction(()=>document.querySelector('.badge')?.textContent.includes('ФАЙЛЫ ОБНОВЛЕНЫ'));
    await page.getByRole('button',{name:'Скопировать запрос'}).click();
    const copied=await app.evaluate(({clipboard})=>clipboard.readText());
    assert.match(copied,/Не менять размер кнопок/);
    await page.locator('nav [data-tab="agents"]').click();
    await page.locator('[data-action="configure-agent"][data-client="claude"]').waitFor();
    await page.locator('[data-action="configure-agent"][data-client="claude"]').click();
    await page.getByRole('heading',{name:'Подключить Claude Code'}).waitFor();
    await page.getByRole('button',{name:'Добавить подключение'}).click();
    await page.waitForFunction(()=>!document.querySelector('#modal').open);
    const configured=JSON.parse(await fs.readFile(path.join(project,'.mcp.json'),'utf8'));
    const spec=Object.values(configured.mcpServers)[0];
    assert.equal(spec.env.ELECTRON_RUN_AS_NODE,'1');
    const mcpClient=new Client({name:'native-agent-test',version:'1.0.0'},{capabilities:{}});
    try {
      await mcpClient.connect(new StdioClientTransport({command:spec.command,args:spec.args,env:spec.env,stderr:'pipe'}));
      const identified=(await mcpClient.callTool({name:'opora_get_project',arguments:{}})).structuredContent;
      const style=(await mcpClient.callTool({name:'opora_get_brandbook',arguments:{project_id:identified.project_id}})).structuredContent;
      const audit=await mcpClient.callTool({name:'opora_review_brandbook',arguments:{project_id:identified.project_id}});
      assert.equal(audit.structuredContent.review.checks.find(c=>c.id==='contrast').status,'pass');
      const reference=await mcpClient.callTool({name:'opora_get_reference',arguments:{project_id:identified.project_id,revision:style.revision,reference_id:style.references[0].id}});
      assert.ok(reference.content.some(c=>c.type==='image' && c.mimeType==='image/png'));
      const submitted=await mcpClient.callTool({name:'opora_report_progress',arguments:{project_id:identified.project_id,revision:style.revision,agent:'claude',request_id:'native-report-0001',phase:'ready_for_review',summary:'MCP report visible in Opora',checks:[{name:'Gameplay test',result:'not_run'}]}});
      assert.ok(!submitted.isError);
      await page.locator('nav [data-tab="brand"]').click();
      await page.getByRole('button',{name:'Заполнить через агента',exact:true}).click();
      await page.waitForFunction(()=>document.querySelector('#toast').textContent==='Запрос скопирован. Вставьте его в подключённого агента.');
      assert.match(await app.evaluate(({clipboard})=>clipboard.readText()),/opora_update_brandbook/);
      const before=(await mcpClient.callTool({name:'opora_get_project',arguments:{}})).structuredContent;
      const filled=await mcpClient.callTool({name:'opora_update_brandbook',arguments:{project_id:before.project_id,revision:before.revision,agent:'claude',request_id:'native-brand-001',summary:'Style proposal via MCP',fields:{direction:'MCP direction received live',fonts:'Game.ttf; body 18 px'}}});
      assert.ok(!filled.isError,JSON.stringify(filled));
      await page.waitForFunction(()=>document.querySelector('[data-field="brand.direction"]')?.value==='MCP direction received live');
      assert.equal(await page.locator('[data-field="brand.status"]').inputValue(),'draft');
      await app.evaluate(({ipcMain})=>{
        global.oporaSaveHandler=ipcMain._invokeHandlers.get('project:save');
        global.oporaSaveWaiting=false;
        const gate=new Promise(resolve=>global.oporaReleaseSave=resolve);
        ipcMain.removeHandler('project:save');
        ipcMain.handle('project:save',async(event,...args)=>{global.oporaSaveWaiting=true;await gate;return global.oporaSaveHandler(event,...args);});
      });
      await page.locator('[data-field="brand.direction"]').fill('Unsaved manual proposal');
      while(!await app.evaluate(()=>global.oporaSaveWaiting))await new Promise(resolve=>setTimeout(resolve,50));
      const fresh=(await mcpClient.callTool({name:'opora_get_project',arguments:{}})).structuredContent;
      const competing=await mcpClient.callTool({name:'opora_update_brandbook',arguments:{project_id:fresh.project_id,revision:fresh.revision,agent:'claude',request_id:'native-brand-002',summary:'Parallel proposal',fields:{direction:'MCP conflict winner'}}});
      assert.ok(!competing.isError);
      await app.evaluate(()=>global.oporaReleaseSave());
      await page.locator('#brand-conflict').waitFor({state:'visible'});
      assert.equal(await page.locator('[data-field="brand.direction"]').inputValue(),'Unsaved manual proposal');
      await page.getByRole('button',{name:'Сравнить версии →'}).click();
      await page.getByRole('heading',{name:'Две версии проекта'}).waitFor();
      await page.getByRole('button',{name:'Принять сохранённую версию'}).click();
      await page.waitForFunction(()=>document.querySelector('#brand-conflict').hidden && document.querySelector('#save-status').textContent==='Сохранено');
      assert.equal(await page.locator('[data-field="brand.direction"]').inputValue(),'MCP conflict winner');
      await app.evaluate(({ipcMain})=>{ipcMain.removeHandler('project:save');ipcMain.handle('project:save',global.oporaSaveHandler);delete global.oporaSaveHandler;delete global.oporaReleaseSave;delete global.oporaSaveWaiting;});
      const latestData=(await mcpClient.callTool({name:'opora_get_project',arguments:{}})).structuredContent;
      const allData=await mcpClient.callTool({name:'opora_update_project',arguments:{project_id:latestData.project_id,revision:latestData.revision,agent:'claude',request_id:'native-project-01',summary:'Game data',fields:{goal:'Goal filled by MCP',tasks:[{id:'agent-task',title:'MCP prototype task',acceptance:'Playable prototype'}],active_task_id:'agent-task',reference_files:['ui/menu.png']}}});
      assert.ok(!allData.isError,JSON.stringify(allData));
      await page.waitForFunction(()=>document.querySelector('#side-active-task').textContent==='MCP prototype task');
      await page.locator('nav [data-tab="overview"]').click();
      assert.equal(await page.locator('[data-field="goal"]').inputValue(),'Goal filled by MCP');
      await page.locator('nav [data-tab="agents"]').click();
    } finally {await mcpClient.close();}
    await page.getByRole('button',{name:'Обновить данные'}).click();
    await page.getByText('MCP report visible in Opora',{exact:true}).waitFor();
    await page.screenshot({path:path.join(__dirname,'../artifacts/agents.png'),fullPage:true});
    const data=await core.loadProject(project);
    assert.equal(data.state.references[0].status,'approved');
    assert.ok((await fs.readFile(path.join(project,'CLAUDE.md'),'utf8')).startsWith('# Existing Claude instructions\nUse existing components.\n'));
    assert.deepEqual(errors,[]);
    await page.locator('nav [data-tab="overview"]').click();
    await page.locator('[data-field="goal"]').fill('Данные сохраняются при закрытии');
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].close());
    await app.waitForEvent('close'); app=null;
    assert.equal((await core.loadProject(project)).state.goal,'Данные сохраняются при закрытии');
    app=await launch();
    const reopened=await app.firstWindow();
    await reopened.waitForFunction(()=>document.querySelector('[data-field="goal"]')?.value === 'Данные сохраняются при закрытии');
    assert.equal(await reopened.locator('#side-name').textContent(),'Native game');
    await reopened.locator('[data-field="name"]').fill('');
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].close());
    await reopened.getByRole('heading',{name:'Изменения не сохранены'}).waitFor();
    await reopened.getByRole('button',{name:'Продолжить работу'}).click();
    await reopened.locator('[data-field="name"]').fill('Native game');
    assert.equal((await core.loadProject(project)).state.brand.direction,'MCP conflict winner');
    console.log('PASS real Electron: brandbook review, contrast correction, task deduplication, copied advice, MCP assessment/image/report, updates and save/restore.');
  } finally {
    if(app) await app.close();
    await fs.rm(temp,{recursive:true,force:true});
  }
}
main().catch(error=>{console.error(error);process.exitCode=1;});
